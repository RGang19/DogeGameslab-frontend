export type PixelIconName = keyof typeof BITMAPS;

function toPath(rows: readonly string[]) {
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x += 1;
        continue;
      }
      let run = 1;
      while (row[x + run] === "#") run += 1;
      d += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(
  Object.entries(BITMAPS).map(([name, rows]) => [
    name,
    { d: toPath(rows), w: Math.max(...rows.map((r) => r.length)), h: rows.length },
  ]),
) as Record<PixelIconName, { d: string; w: number; h: number }>;

type PixelIconProps = Omit<SVGProps<SVGSVGElement>, "name"> & {
  name: PixelIconName;
  /** Rendered height in px; width follows the bitmap's aspect. */
  size?: number;
};

export const PixelIcon = memo(function PixelIcon({
  name,
  size = 16,
  className = "",
  ...props
}: PixelIconProps) {
  const icon = PATHS[name];
  // Pad to a square box so icons of different bitmap sizes line up.
  const box = Math.max(icon.w, icon.h);
  const dx = (box - icon.w) / 2;
  const dy = (box - icon.h) / 2;
  return (
    <svg
      viewBox={`${-dx} ${-dy} ${box} ${box}`}
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      className={`shrink-0 ${className}`}
      {...props}
    >
      <path d={icon.d} />
    </svg>
  );
});
